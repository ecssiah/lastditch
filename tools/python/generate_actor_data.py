#!/usr/bin/env python3

import argparse
import re
import sys
import yaml

from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import NoReturn


@dataclass(frozen=True)
class NationDefinition:
    name: str
    texture: str


@dataclass(frozen=True)
class Configuration:
    version: int
    nation_types: tuple[NationDefinition, ...]


NAME_PATTERN = re.compile(r"[a-z][a-z0-9]*(?:_[a-z0-9]+)*")


def load_yaml(path: Path) -> object:
    try:
        with path.open(encoding="utf-8") as file:
            return yaml.safe_load(file)
    except OSError as error:
        raise RuntimeError(f"cannot read {path}: {error}") from error
    except yaml.YAMLError as error:
        raise RuntimeError(f"invalid YAML in {path}: {error}") from error


def config_error(location: str, message: str) -> NoReturn:
    raise RuntimeError(f"{location}: {message}")


def validate_name(value: object, location: str) -> str:
    if not isinstance(value, str):
        config_error(location, "expected a string")

    if NAME_PATTERN.fullmatch(value) is None:
        config_error(
            location,
            "expected a lowercase name containing letters, digits, "
            "and single underscores"
        )

    return value


def parse_config(document: object) -> Configuration:
    if not isinstance(document, Mapping):
        config_error("<root>", "expected a mapping")

    required_root_fields = {"version", "nation_types"}

    unknown_root_fields = set(document) - required_root_fields
    if unknown_root_fields:
        names = ", ".join(
            sorted(repr(field) for field in unknown_root_fields)
        )
        config_error("<root>", f"unknown fields: {names}")

    missing_root_fields = required_root_fields - set(document)
    if missing_root_fields:
        names = ", ".join(sorted(missing_root_fields))
        config_error("<root>", f"missing fields: {names}")

    version = document["version"]

    if type(version) is not int:
        config_error("version", "expected an integer")

    if version != 1:
        config_error(
            "version",
            f"unsupported version {version}; expected 1"
        )

    raw_nation_types = document["nation_types"]
    if not isinstance(raw_nation_types, Mapping):
        config_error("nation_types", "expected a mapping")

    if not raw_nation_types:
        config_error("nation_types", "must contain at least one nation type")

    nation_types: list[NationDefinition] = []

    for raw_nation_name, raw_nation in raw_nation_types.items():
        nation_name = validate_name(
            raw_nation_name,
            "nation_types.<name>",
        )
        nation_location = f"nation_types.{nation_name}"

        if not isinstance(raw_nation, Mapping):
            config_error(nation_location, "expected a mapping")

        allowed_nation_fields = {"texture"}
        unknown_nation_fields = set(raw_nation) - allowed_nation_fields
        if unknown_nation_fields:
            names = ", ".join(
                sorted(repr(field) for field in unknown_nation_fields)
            )
            config_error(nation_location, f"unknown fields: {names}")

        if "texture" not in raw_nation:
            config_error(nation_location, "missing field 'texture'")

        texture = validate_name(
            raw_nation["texture"],
            f"{nation_location}.texture",
        )

        nation_types.append(
            NationDefinition(name=nation_name, texture=texture)
        )

    return Configuration(
        version=version,
        nation_types=tuple(nation_types),
    )


RULE = "// " + "=" * 76
LINE = "// " + "-" * 76


def storage_type(count: int) -> str:
    """Smallest unsigned type that can hold every key of a table."""
    if count <= 1 << 8:
        return "u8"

    if count <= 1 << 16:
        return "u16"

    return "u32"


def banner(filename: str, purpose: list[str]) -> list[str]:
    lines = [
        RULE,
        f"// File:    generated/{filename}",
        "// Layer:   app",
    ]

    for index, text in enumerate(purpose):
        prefix = "// Purpose: " if index == 0 else "//          "
        lines.append(prefix + text)

    lines.extend([RULE, ""])

    return lines


def generate_header(config: Configuration) -> str:
    nation_storage = storage_type(len(config.nation_types))

    lines = banner("actor_data.generated.h", [
        "Nation type reference tables.",
        "Generated by tools/python/generate_actor_data.py from",
        "data/actor_data.yml. Do not edit; edit the YAML file instead.",
    ])

    lines.extend([
        "#ifndef ACTOR_DATA_GENERATED_H",
        "#define ACTOR_DATA_GENERATED_H",
        "",
        '#include "core/types.h"',
        "",
        LINE,
        "// Enum:    NationTypeId",
        "// Purpose: Keys of the nation type reference tables.",
        LINE,
        "typedef enum NationTypeId",
        "{",
    ])

    for nation in config.nation_types:
        constant = f"NATION_TYPE_{nation.name.upper()},"
        lines.append(f'    {constant:<32}// Nation "{nation.name}".')

    lines.extend([
        f"    {'NATION_TYPE_COUNT':<32}// Number of nations.",
        "} NationTypeId;",
        "",
        LINE,
        "// Type:    NationType",
        "// Purpose: Storage type of a NationTypeId in tables; the narrowest type",
        "//          that holds every key.",
        LINE,
        f"typedef {nation_storage} NationType;",
        "",
        LINE,
        "// Reference: NATION_TYPE_NAME",
        "// Purpose:   Name of each nation.",
        "// Key:       NationTypeId",
        "// Order:     rows in NationTypeId order",
        "// Lifetime:  compiled in, read-only",
        LINE,
        "extern const char* const NATION_TYPE_NAME[NATION_TYPE_COUNT];",
        "",
        LINE,
        "// Reference: NATION_TEXTURE_NAME",
        "// Purpose:   Base name of the texture file, under assets/textures/actor,",
        "//            worn by the actors of each nation.",
        "// Key:       NationTypeId",
        "// Order:     rows in NationTypeId order",
        "// Lifetime:  compiled in, read-only",
        LINE,
        "extern const char* const NATION_TEXTURE_NAME[NATION_TYPE_COUNT];",
        "",
        "#endif",
        "",
    ])

    return "\n".join(lines)


def generate_source(config: Configuration) -> str:
    lines = banner("actor_data.generated.c", [
        "Rows of the nation type reference tables.",
        "Generated by tools/python/generate_actor_data.py from",
        "data/actor_data.yml. Do not edit; edit the YAML file instead.",
    ])

    lines.extend([
        '#include "actor_data.generated.h"',
        "",
        "const char* const NATION_TYPE_NAME[NATION_TYPE_COUNT] =",
        "{",
    ])

    for index, nation in enumerate(config.nation_types):
        separator = "," if index + 1 < len(config.nation_types) else ""
        lines.append(f'    "{nation.name}"{separator}')

    lines.extend([
        "};",
        "",
        "const char* const NATION_TEXTURE_NAME[NATION_TYPE_COUNT] =",
        "{",
    ])

    for index, nation in enumerate(config.nation_types):
        separator = "," if index + 1 < len(config.nation_types) else ""
        lines.append(f'    "{nation.texture}"{separator}')

    lines.extend([
        "};",
        "",
    ])

    return "\n".join(lines)


def write_if_changed(path: Path, contents: str) -> None:
    try:
        if path.read_text(encoding="utf-8") == contents:
            return
    except FileNotFoundError:
        pass

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(contents, encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate C actor data from YAML."
    )
    parser.add_argument("input_path", type=Path)
    parser.add_argument("output_header_path", type=Path)
    parser.add_argument("output_source_path", type=Path)
    arguments = parser.parse_args()

    document = load_yaml(arguments.input_path)
    config = parse_config(document)
    write_if_changed(arguments.output_header_path, generate_header(config))
    write_if_changed(arguments.output_source_path, generate_source(config))


if __name__ == "__main__":
    try:
        main()
    except RuntimeError as error:
        print(f"generate_actor_data: error: {error}", file=sys.stderr)
        raise SystemExit(1)
